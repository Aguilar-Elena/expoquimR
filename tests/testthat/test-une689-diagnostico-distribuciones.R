test_that('diagnostic compares both distributions without changing core assessment', {
  ed <- c(3, 4, 5, 6, 8, 12)
  old <- une689_evaluate_statistical(ed, 15)
  d <- une689_compare_distributions(ed, 15)
  expect_identical(d$models$model, c('Normal', 'Lognormal'))
  expect_true(all(d$models$not_rejected))
  expect_true(d$discordant)
  expect_true(d$requires_review)
  expect_equal(d$models$lsc, c(13.47605, 16.85801), tolerance = 1e-4)
  expect_identical(d$models$mathematical_decision, c('CONFORMITY', 'NON-CONFORMITY'))
  expect_identical(une689_evaluate_statistical(ed, 15), old)
})
test_that('diagnostic rejects unsupported or degenerate inputs', {
  expect_error(une689_compare_distributions(rep(1, 6), 10), 'Constant')
  expect_error(une689_compare_distributions(1:5, 10), 'At least six')
  expect_error(une689_compare_distributions(1:31, 10), 'n > 30')
  expect_error(une689_compare_distributions(1:6, 0), 'strictly positive')
  expect_error(une689_compare_distributions(1:6, 10, alpha = 1), 'between 0 and 1')
})
